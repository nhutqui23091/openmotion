// The interface-colour ratchet (R12, AE2): a per-file baseline of colour literals that only ever
// goes down. It counts the three ways a feature can still write interface colour outside the shared
// theme: hex and functional colour values in code, palette utilities such as `bg-slate-900` in a
// class string, and `backdrop-blur` utilities. Palette and blur are counted because most Studio
// interface colour lives in Tailwind class strings, where a hex counter sees nothing, and because
// the shared controls in packages/open-design-ui carry the same strings.
// Per file so two sweep PRs touching one file conflict on its line and force a recount.
// The baseline is never regenerated by a normal run: a missing one fails, and rewriting it needs
// the named flag, so the number in git is one a human accepted.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { listSourceFiles, REPO_ROOT, STYLES_DIR } from "./styleSources";

const BASELINE_PATH = path.join(STYLES_DIR, "hex-baseline.json");

const WRITE_FLAG = "HEX_BASELINE_WRITE";
const LOWER_COMMAND = `${WRITE_FLAG}=1 bunx vitest run src/styles/hexRatchet.test.ts`;

type Kind = "hex" | "palette" | "blur";
type Counts = Record<Kind, number>;

const KINDS: readonly Kind[] = ["hex", "palette", "blur"];
const LABEL: Readonly<Record<Kind, string>> = {
  hex: "hex colours",
  palette: "palette utilities",
  blur: "backdrop-blur utilities",
};

// A literal colour: `#abc`, `#aabbcc`, `#aabbccdd`, or functional notation. This test owns the
// regex, so the baseline is whatever this rule sees.
const HEX_LITERAL = /#(?:[0-9a-f]{8}|[0-9a-f]{6}|[0-9a-f]{3,4})\b|\b(?:rgba?|hsla?)\(/gi;

// A palette utility in a class string. The stem has to start a class token, so hyphenated prose
// such as "pink-to-cyan gradient" does not read as the `to-cyan` utility. The directional and offset
// forms are covered (`border-t-`, `ring-offset-`, `divide-x-`), while widths such as `border-t-2`
// stay out of the count.
const PALETTE_UTILITY =
  /(?<![\w-])(?:bg|text|border|divide|ring|outline|decoration|shadow|accent|caret|fill|stroke|from|via|to|placeholder)(?:-[trblxyse])?(?:-offset)?-(?:slate|gray|grey|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose|black|white)(?:-\d{2,3})?(?:\/\d{1,3})?\b/g;

const BLUR_UTILITY = /(?<![\w-])backdrop-blur(?:-\w+)?\b/g;

/** Files whose whole job is to hold colour values. */
function isTokenSource(relative: string): boolean {
  return /styles\/(theme\.css|tailwind-preset\.shared\.js|tailwind-preset\.ts)$/.test(relative);
}

function isScanned(relative: string): boolean {
  if (isTokenSource(relative) || /\.test\.tsx?$/.test(relative)) return false;
  return /\.(tsx?|css)$/.test(relative);
}

/** Strings match first and are kept, so `"image/*"` or `"a//b"` never opens a comment. */
const STRING_OR_COMMENT =
  /("(?:\\.|[^"\\\n])*"|'(?:\\.|[^'\\\n])*'|`(?:\\.|[^`\\])*`)|\/\*[\s\S]*?\*\/|\/\/[^\n]*/g;

/** Comments hold issue numbers like `#2291` that read as hex, and prose that names a banned class. */
function stripComments(text: string, lineComments: boolean): string {
  return text.replace(STRING_OR_COMMENT, (match, string?: string) => {
    if (string !== undefined) return match;
    return match.startsWith("//") && !lineComments ? match : "";
  });
}

function countLiterals(text: string, lineComments = true): Counts {
  const code = stripComments(text, lineComments);
  return {
    hex: [...code.matchAll(HEX_LITERAL)].length,
    palette: [...code.matchAll(PALETTE_UTILITY)].length,
    blur: [...code.matchAll(BLUR_UTILITY)].length,
  };
}

const empty = (): Counts => ({ hex: 0, palette: 0, blur: 0 });

/** Repository-relative path to the per-kind counts, for every scanned file that has one. */
function scan(): Map<string, Counts> {
  const counts = new Map<string, Counts>();
  for (const [file, text] of listSourceFiles(isScanned, REPO_ROOT)) {
    const value = countLiterals(text, !file.endsWith(".css"));
    if (KINDS.some(kind => value[kind] > 0)) counts.set(file, value);
  }
  return counts;
}

interface Baseline {
  readonly total: Counts;
  /** Only the kinds a file actually has, so the baseline stays a list of known exceptions. */
  readonly files: Readonly<Record<string, Partial<Counts>>>;
}

function toBaseline(counts: ReadonlyMap<string, Counts>): Baseline {
  const files: Record<string, Partial<Counts>> = {};
  const total = empty();
  for (const key of [...counts.keys()].sort()) {
    const value = counts.get(key) ?? empty();
    const entry: Partial<Counts> = {};
    for (const kind of KINDS) {
      if (value[kind] > 0) entry[kind] = value[kind];
      total[kind] += value[kind];
    }
    if (Object.keys(entry).length > 0) files[key] = entry;
  }
  return { total, files };
}

/** Every file and kind whose count moved, split by direction. */
function compare(counts: ReadonlyMap<string, Counts>, baseline: Baseline) {
  const risen: string[] = [];
  const fallen: string[] = [];
  // A file missing from the baseline has a baseline of zero, so a rename cannot smuggle its
  // literals past the ratchet.
  for (const [file, value] of counts) {
    for (const kind of KINDS) {
      const allowed = baseline.files[file]?.[kind] ?? 0;
      if (value[kind] > allowed) risen.push(`${file}: ${value[kind]} ${LABEL[kind]}, baseline ${allowed}`);
      if (value[kind] < allowed) fallen.push(`${file}: ${LABEL[kind]} down to ${value[kind]}, baseline ${allowed}`);
    }
  }
  for (const [file, entry] of Object.entries(baseline.files)) {
    // A file that is still scanned reports its own per-kind drop above; this loop covers a file that
    // left the scan entirely, so one drop is never reported twice.
    if (counts.has(file)) continue;
    for (const kind of KINDS) {
      const allowed = entry[kind] ?? 0;
      if (allowed > 0) fallen.push(`${file}: ${LABEL[kind]} now 0, baseline ${allowed}`);
    }
  }
  return { risen, fallen };
}

// A rise is a failure. A fall is reported with the command that banks it, because a baseline left
// high is a budget the next change can spend.
function verdict(counts: ReadonlyMap<string, Counts>, baseline: Baseline | undefined): string[] {
  if (baseline === undefined) {
    return [`src/styles/hex-baseline.json is missing. Write it with: ${LOWER_COMMAND}`];
  }
  const { risen, fallen } = compare(counts, baseline);
  if (risen.length > 0) {
    return [
      "Interface colours belong in packages/design-system/tokens.json.",
      ...risen,
      `If these are unavoidable, lower is the only direction: ${LOWER_COMMAND}`,
    ];
  }
  if (fallen.length > 0) return [`Colour literals went down. Bank it: ${LOWER_COMMAND}`, ...fallen];
  return [];
}

function readBaseline(): Baseline | undefined {
  if (!existsSync(BASELINE_PATH)) return undefined;
  return JSON.parse(readFileSync(BASELINE_PATH, "utf8")) as Baseline;
}

describe("interface colour counter", () => {
  it("counts a hex in a style object, in canvas code and in a stylesheet", () => {
    expect(countLiterals(`<div style={{ background: "#161618" }} />`)).toEqual({ hex: 1, palette: 0, blur: 0 });
    expect(countLiterals(`context.fillStyle = "#090b0e";`)).toEqual({ hex: 1, palette: 0, blur: 0 });
    expect(countLiterals(`.ring { box-shadow: 0 0 0 1px rgb(110 231 183); }`)).toEqual({ hex: 1, palette: 0, blur: 0 });
    expect(countLiterals(`a { color: rgba(0, 0, 0, 0.5); border-color: hsl(0 0% 4%); }`)).toEqual({ hex: 2, palette: 0, blur: 0 });
  });

  it("does not mistake a fragment or an issue number for a colour", () => {
    // Known limit: an identifier that is exactly 3, 4, 6 or 8 hex characters in code reads as a
    // colour; the baseline absorbs it.
    expect(countLiterals(`href="#section-two" // see #12345`)).toEqual(empty());
  });

  it("keeps a colour that follows comment-shaped text inside a string", () => {
    expect(countLiterals(`accept="image/*"; const c = "#161618"; x = "*/";`)).toEqual({ hex: 1, palette: 0, blur: 0 });
    expect(countLiterals("const u = `x//y`; const c = '#161618';")).toEqual({ hex: 1, palette: 0, blur: 0 });
    expect(countLiterals(`.a { background: url(//cdn.test/a.png) #161618; }`, false)).toEqual({ hex: 1, palette: 0, blur: 0 });
  });

  it("ignores a colour-shaped issue number in a line or block comment", () => {
    expect(countLiterals(`const a = 1; // decision (#2291)`)).toEqual(empty());
    expect(countLiterals(`/** see #2291 and rgba(0,0,0,1) */\nconst a = 1;`)).toEqual(empty());
    expect(countLiterals(`fetch("https://x.test/#abc"); const c = "#161618"; // #2291`)).toEqual({ hex: 2, palette: 0, blur: 0 });
  });

  it("counts palette and blur utilities written into a class string", () => {
    expect(countLiterals(`<div className="bg-slate-900 text-white/70 backdrop-blur-md" />`)).toEqual({ hex: 0, palette: 2, blur: 1 });
    expect(countLiterals(`const style = "lg:hover:border-t-red-500 ring-offset-2";`)).toEqual({ hex: 0, palette: 1, blur: 0 });
    expect(countLiterals(`.panel { @apply divide-x-stone-200; }`, false)).toEqual({ hex: 0, palette: 1, blur: 0 });
  });

  it("does not read hyphenated prose or a width utility as a palette utility", () => {
    expect(countLiterals(`const copy = "pink-to-cyan gradient bubbles";`)).toEqual(empty());
    expect(countLiterals(`className="border-t-2 ring-2 backdrop-blur"`)).toEqual({ hex: 0, palette: 0, blur: 1 });
  });

  it("ignores palette and blur mentions inside comments", () => {
    expect(countLiterals(`// never add bg-slate-900 or backdrop-blur-md here\nconst a = 1;`)).toEqual(empty());
    expect(countLiterals(`/* bg-slate-900 */ const className = "text-stone-700";`)).toEqual({ hex: 0, palette: 1, blur: 0 });
  });

  it("leaves the token sources and the tests out of the scan", () => {
    expect(isScanned("packages/studio/src/styles/theme.css")).toBe(false);
    expect(isScanned("packages/studio/src/styles/tailwind-preset.shared.js")).toBe(false);
    expect(isScanned("packages/studio/src/styles/theme.test.ts")).toBe(false);
    expect(isScanned("packages/studio/src/components/ui/Button.tsx")).toBe(true);
    expect(isScanned("packages/open-design-ui/button.tsx")).toBe(true);
  });
});

describe("interface colour ratchet", () => {
  const baseline: Baseline = { total: { hex: 0, palette: 2, blur: 0 }, files: { "a.tsx": { palette: 2 } } };

  it("fails when a file's count rises, naming the file, the kind and both numbers", () => {
    // Covers AE2.
    const message = verdict(new Map([["a.tsx", { hex: 0, palette: 3, blur: 0 }]]), baseline).join("\n");

    expect(message).toContain("a.tsx: 3 palette utilities, baseline 2");
    expect(message).toContain(LOWER_COMMAND);
  });

  it("fails for a blur utility the baseline does not carry", () => {
    const message = verdict(new Map([["a.tsx", { hex: 0, palette: 2, blur: 1 }]]), baseline).join("\n");

    expect(message).toContain("a.tsx: 1 backdrop-blur utilities, baseline 0");
  });

  it("passes when a count falls and says how to bank it", () => {
    const message = verdict(new Map([["a.tsx", { hex: 0, palette: 1, blur: 0 }]]), baseline).join("\n");

    expect(message).toContain("Colour literals went down");
    expect(message).toContain("a.tsx: palette utilities down to 1, baseline 2");
    expect(message).toContain(LOWER_COMMAND);
  });

  it("reports a kind that falls to zero once", () => {
    const mixed: Baseline = { total: { hex: 0, palette: 2, blur: 0 }, files: { "a.tsx": { hex: 1, palette: 2 } } };
    const fallen = verdict(new Map([["a.tsx", { hex: 1, palette: 0, blur: 0 }]]), mixed).join("\n")
      .split("\n").filter(line => line.includes("palette"));

    expect(fallen).toEqual(["a.tsx: palette utilities down to 0, baseline 2"]);
  });

  it("reports a file that left the scan once per recorded kind", () => {
    const gone: Baseline = { total: { hex: 1, palette: 2, blur: 0 }, files: { "a.tsx": { hex: 1, palette: 2 } } };
    const fallen = verdict(new Map(), gone).join("\n").split("\n").slice(1);

    expect(fallen).toEqual(["a.tsx: hex colours now 0, baseline 1", "a.tsx: palette utilities now 0, baseline 2"]);
  });

  it("treats a file the baseline has never seen as a baseline of zero", () => {
    const zero: Baseline = { total: empty(), files: {} };

    expect(verdict(new Map([["new.tsx", empty()]]), zero)).toEqual([]);
    expect(verdict(new Map([["new.tsx", { hex: 0, palette: 1, blur: 0 }]]), zero).join("\n")).toContain(
      "new.tsx: 1 palette utilities, baseline 0",
    );
  });

  it("round-trips: a baseline written from a scan accepts that same scan", () => {
    const counts = new Map([
      ["b.css", { hex: 4, palette: 0, blur: 0 }],
      ["a.tsx", { hex: 2, palette: 5, blur: 1 }],
    ]);
    const written = toBaseline(counts);

    expect(Object.keys(written.files)).toEqual(["a.tsx", "b.css"]);
    expect(written.total).toEqual({ hex: 6, palette: 5, blur: 1 });
    expect(verdict(counts, written)).toEqual([]);
  });

  it("fails with the flag named when there is no baseline at all", () => {
    expect(verdict(new Map([["a.tsx", empty()]]), undefined).join("\n")).toContain(`${WRITE_FLAG}=1`);
  });

  it("holds Studio and the shared controls at or below the committed baseline", () => {
    const counts = scan();
    if (process.env[WRITE_FLAG] === "1") {
      writeFileSync(BASELINE_PATH, `${JSON.stringify(toBaseline(counts), null, 2)}\n`);
    }
    const committed = readBaseline();

    expect(verdict(counts, committed)).toEqual([]);
  });
});
